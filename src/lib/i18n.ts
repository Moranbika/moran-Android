export type ResolvedLanguage = 'zh' | 'en';

export function resolveLanguage(preference: LanguagePreference, systemLanguage = ''): ResolvedLanguage {
  if (preference === 'zh' || preference === 'en') return preference;
  return /^zh\b/i.test(systemLanguage) ? 'zh' : 'en';
}

