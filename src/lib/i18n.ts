function bookGradeLabel(value: string): string {
  return value
    .replace(/一年级/g, 'Grade 1')
    .replace(/二年级/g, 'Grade 2')
    .replace(/三年级/g, 'Grade 3')
    .replace(/四年级/g, 'Grade 4')
    .replace(/五年级/g, 'Grade 5')
    .replace(/六年级/g, 'Grade 6')
    .replace(/七年级/g, 'Grade 7')
    .replace(/八年级/g, 'Grade 8')
    .replace(/九年级/g, 'Grade 9')
    .replace(/必修第一册/g, 'Compulsory 1')
    .replace(/必修第二册/g, 'Compulsory 2')
    .replace(/必修第三册/g, 'Compulsory 3')
    .replace(/选择性必修第一册/g, 'Selective Compulsory 1')
    .replace(/上册/g, 'A')
    .replace(/下册/g, 'B')
    .replace(/第一册/g, 'Book 1')
    .replace(/第二册/g, 'Book 2');
}

